"""Offline catalog validation and deterministic organization-profile rendering."""
import argparse
import html
import json
from pathlib import Path
import re
import sys
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parents[2]
AREAS = {
    "framework": "Framework",
    "suites": "Suites",
    "applications": "Applications",
    "learn": "Learn",
    "community": "Community projects",
    "infrastructure": "Distribution & infrastructure",
    "forks": "Upstream forks",
}
KINDS = {"product", "app", "example", "learning", "community", "infra", "fork"}
REQUIRED = {"name", "area", "kind", "summary", "depends_on", "status"}
OPTIONAL = {"packaged", "site", "pinned", "accent", "note", "upstream", "confirm"}
NAME = re.compile(r"[A-Za-z0-9_.-]+")
UPSTREAM = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9_.-]+")


def validate(catalog):
    """Return all errors, without suppressing later entries after a failure."""
    errors = []
    if not isinstance(catalog, list):
        return ["catalog must be a list"]
    names = set()
    for index, entry in enumerate(catalog):
        label = f"entry {index + 1}"
        if not isinstance(entry, dict):
            errors.append(f"{label}: must be a mapping")
            continue
        for key in sorted(REQUIRED - entry.keys()):
            errors.append(f"{label}: missing {key}")
        for key in sorted(entry.keys() - REQUIRED - OPTIONAL, key=str):
            errors.append(f"{label}: unknown identity field {key}")
        name = entry.get("name")
        if not isinstance(name, str) or not NAME.fullmatch(name):
            errors.append(f"{label}: invalid name")
        elif name in names:
            errors.append(f"{label}: duplicate name {name}")
        else:
            names.add(name)
        for key, choices in [("area", AREAS), ("kind", KINDS),
                             ("status", {"active", "retiring", "retired"})]:
            if not isinstance(entry.get(key), str) or entry[key] not in choices:
                errors.append(f"{label}: unknown {key}")
        for key in ["summary", "accent", "note", "upstream"]:
            if key in entry and (not isinstance(entry[key], str)
                                 or not entry[key].strip()
                                 or any(c in entry[key] for c in "\r\n")):
                errors.append(f"{label}: {key} must be non-empty, single-line text")
        for key in ["packaged", "site", "pinned", "confirm"]:
            if key in entry and type(entry[key]) is not bool:
                errors.append(f"{label}: {key} must be a boolean")
        if "accent" in entry and entry.get("kind") != "product":
            errors.append(f"{label}: accent is allowed only on products")
        if entry.get("kind") == "fork":
            if not isinstance(entry.get("upstream"), str) or not UPSTREAM.fullmatch(entry["upstream"]):
                errors.append(f"{label}: forks require upstream owner/repo")
            if entry.get("status") != "active":
                errors.append(f"{label}: upstream forks must stay active")
        deps = entry.get("depends_on")
        if not isinstance(deps, list) or any(not isinstance(dep, str) for dep in deps):
            errors.append(f"{label}: depends_on must be a list of names")
    for index, entry in enumerate(catalog):
        if isinstance(entry, dict) and isinstance(entry.get("depends_on"), list):
            for dep in entry["depends_on"]:
                if isinstance(dep, str) and dep not in names:
                    errors.append(f"entry {index + 1}: unknown dependency {dep}")
    return errors


def text(value):
    """Escape authored text for Markdown table cells; never interpret HTML."""
    value = html.escape(value, quote=False)
    return re.sub(r"([\\|\[\]*_`])", r"\\\1", value)


def repo_url(name):
    return f"https://github.com/SNodeC/{quote(name, safe='')}"


def render_profile(catalog, metadata):
    errors = validate(catalog)
    if errors:
        raise ValueError("\n".join(errors))
    branch = quote(metadata[".github"]["default_branch"], safe="")
    control = f"{repo_url('.github')}/blob/{branch}"
    lines = [
        "<!-- Generated by tools/snodec_sync profile; edit catalog.yml, not this file. -->",
        f'<img src="{control}/brand/snodec-mark.svg?raw=true" alt="SNode.C mark" width="96">',
        "",
        "# SNode.C",
        "",
        "An ecosystem for building event-driven networked programs in C++ and running MQTT infrastructure.",
        "",
        "## Start here",
        "",
        f"- **Build networked programs:** [SNode.C]({repo_url('snode.c')})",
        f"- **Run MQTT infrastructure:** [MQTTSuite]({repo_url('mqttsuite')})",
        f"- **Learn:** [Book companion]({repo_url('SNode.C-Book-Companion')}) and [examples](#learn)",
        f"- **Install:** [Packages]({repo_url('Packages')})",
        "",
    ]

    def table(entries, forks=False):
        result = ["| Repository | Purpose | CI | Latest release |",
                  "| --- | --- | --- | --- |"]
        for entry in entries:
            name = entry["name"]
            info = metadata.get(name, {})
            purpose = text(entry["summary"])
            if "note" in entry:
                purpose += f"<br>_{text(entry['note'])}_"
            if forks:
                purpose += f"<br>[Upstream](https://github.com/{entry['upstream']})"
            if entry["status"] != "active":
                purpose += f"<br>_{entry['status'].title()}_"
            workflow = info.get("workflow")
            badge = ""
            if workflow:
                url = f"{repo_url(name)}/actions/workflows/{quote(Path(workflow).name, safe='')}"
                default = quote(info["default_branch"], safe="")
                badge = f"[![CI]({url}/badge.svg?branch={default})]({url})"
            release = info.get("release")
            latest = ""
            if release:
                tag = release["tag"]
                latest = f"[{text(tag)}]({repo_url(name)}/releases/tag/{quote(tag, safe='')})"
                if release["prerelease"]:
                    latest += " (pre-release)"
            result.append(f"| [{text(name)}]({repo_url(name)}) | {purpose} | {badge} | {latest} |")
        return result + [""]

    for area, title in AREAS.items():
        if area == "forks":
            continue
        entries = [e for e in catalog if e["area"] == area and e["status"] == "active"]
        lines += [f"## {title}", ""] + table(entries)
    forks = [e for e in catalog if e["kind"] == "fork"]
    lines += ["<details>", "<summary>Upstream forks — kept for future work</summary>", ""]
    lines += table(forks, forks=True) + ["</details>", ""]
    archived = [e for e in catalog if e["status"] != "active"]
    lines += ["<details>", "<summary>Archive</summary>", ""]
    for area, title in AREAS.items():
        entries = [e for e in archived if e["area"] == area]
        if entries:
            lines += [f"### {title}", ""] + table(entries)
    lines += [
        "</details>", "", "---", "",
        "Maintainer: [Volker Christian](https://github.com/VolkerChristian).",
        f"[Contributing]({control}/CONTRIBUTING.md) · [Security]({control}/SECURITY.md)",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["check", "profile"])
    parser.add_argument("--catalog", type=Path, default=ROOT / "catalog.yml")
    parser.add_argument("--metadata", type=Path, default=ROOT / "profile/github-metadata.json")
    parser.add_argument("--output", type=Path, default=ROOT / "profile/README.md")
    args = parser.parse_args(argv)
    try:
        catalog = yaml.safe_load(args.catalog.read_text(encoding="utf-8"))
        if args.command == "check":
            errors = validate(catalog)
            if errors:
                raise ValueError("\n".join(errors))
        else:
            metadata = json.loads(args.metadata.read_text(encoding="utf-8"))
            args.output.write_text(render_profile(catalog, metadata), encoding="utf-8")
    except (OSError, ValueError, KeyError, yaml.YAMLError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
